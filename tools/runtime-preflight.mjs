import fs from 'node:fs';
import net from 'node:net';
import dns from 'node:dns/promises';
import { spawnSync } from 'node:child_process';

const results = [];
const add = (name, status, detail) => results.push({ name, status, detail });

function command(name, args = ['--version']) {
  const r = spawnSync(name, args, { encoding: 'utf8', shell: process.platform === 'win32' });
  return { ok: r.status === 0, text: `${r.stdout || ''}${r.stderr || ''}`.trim() };
}

const major = Number(process.versions.node.split('.')[0]);
add('Node.js >= 20', major >= 20 ? 'PASS' : 'FAIL', `v${process.versions.node}`);
const npm = command('npm');
add('npm', npm.ok ? 'PASS' : 'FAIL', npm.text || 'not found');
const docker = command('docker');
add('Docker', docker.ok ? 'PASS' : 'FAIL', docker.text || 'not found');
const compose = command('docker', ['compose', 'version']);
add('Docker Compose', compose.ok ? 'PASS' : 'FAIL', compose.text || 'not found');

try {
  const r = await dns.lookup('registry.npmjs.org');
  add('npm registry DNS', 'PASS', r.address);
} catch (error) {
  add('npm registry DNS', 'FAIL', error?.code || error?.message || String(error));
}

const requiredFiles = ['package.json', '.env.example', 'docker-compose.yml', 'services/api/package.json', 'apps/web/package.json', 'apps/seller/package.json', 'apps/admin/package.json'];
for (const file of requiredFiles) add(`file ${file}`, fs.existsSync(file) ? 'PASS' : 'FAIL', fs.existsSync(file) ? 'present' : 'missing');
add('.env', fs.existsSync('.env') ? 'PASS' : 'WARN', fs.existsSync('.env') ? 'present' : 'copy .env.example to .env before starting');
add('node_modules', fs.existsSync('node_modules') ? 'PASS' : 'WARN', fs.existsSync('node_modules') ? 'installed' : 'run npm install');
add('package-lock.json', fs.existsSync('package-lock.json') ? 'PASS' : 'WARN', fs.existsSync('package-lock.json') ? 'present' : 'will be generated by npm install; commit it after a successful install');

async function portState(port) {
  return await new Promise(resolve => {
    const socket = net.createConnection({ host: '127.0.0.1', port });
    socket.setTimeout(500);
    socket.on('connect', () => { socket.destroy(); resolve('IN_USE'); });
    socket.on('timeout', () => { socket.destroy(); resolve('FREE'); });
    socket.on('error', () => resolve('FREE'));
  });
}
for (const port of [3000,3001,3002,4000,27017,6379,9000,9001]) {
  const state = await portState(port);
  add(`port ${port}`, 'INFO', state === 'IN_USE' ? 'already listening (okay if stack is running)' : 'free');
}

for (const r of results) console.log(`${r.status.padEnd(5)} ${r.name}: ${r.detail}`);
const failures = results.filter(r => r.status === 'FAIL');
if (failures.length) {
  console.error(`\nPreflight found ${failures.length} blocking prerequisite(s).`);
  process.exitCode = 1;
} else {
  console.log('\nPreflight prerequisites look usable.');
}
